// The calm badge an effect wears when the frame it drew was not its own work.
//
// The engine sends a *key*, not a sentence (`BADGE_REASONS` in
// `crates/lumit-bridge/src/api/effect.rs`): five things it can say, four of them
// about somebody else's code or about an effect this build has never heard of,
// and one about a shader the user is still writing.
// `test/l10n/engine_labels_test.dart` reads that declaration and fails if a
// reason has no case below.

/// The badge sentence for [key], or null when this build has none — the caller
/// then draws nothing rather than a raw key. [detail] is the engine's line
/// beneath, which a missing LFX effect's sentence names instead.
String? effectBadge(String key, [String? detail]) {
  switch (key) {
    case 'plugin_failed':
      return l10n.badgePluginFailed;
    // Voice isolation given more sound than it will take. The sound plays
    // unchanged, and the headline says what to do.
    case 'too_long':
      return l10n.badgeVoiceTooLong;
    case 'plugin_disabled':
      return l10n.badgePluginDisabled;
    case 'plugin_missing':
      return l10n.badgePluginMissing;
    case 'unknown_effect':
      return l10n.badgeUnknownEffect;
    // The one built-in that can wear a badge: a Custom shader whose text does
    // not compile (docs/impl/custom-shader.md §2.2). The compiler's own
    // sentence goes in the detail slot beneath, untranslated.
    case 'shader_failed':
      return l10n.badgeShaderFailed;
    // A Clone deformer set to Vector with no outlines to read. Why is
    // written beneath.
    case 'clone_vector_reads_picture':
      return l10n.badgeCloneVectorReadsPicture;
    // An effect that asks a trained model for a plane, on a machine without
    // the addon (docs/impl/addons.md §6.1). The detail slot beneath names
    // which one to install, untranslated, because it is an addon id.
    case 'addon_missing':
      return l10n.badgeAddonMissing;
    // An LFX effect no installed extension carries. The detail is the
    // extension's id, said in the sentence.
    case 'lfx_missing':
      return l10n.badgeLfxMissing(detail ?? '');
    // An LFX effect the graphics device was lost under twice, switched off
    // until Lumit restarts.
    case 'lfx_struck_off':
      return l10n.badgeLfxStruckOff;
    default:
      return null;
  }
}

/// Whether this build has a sentence for [key] — what the sync test asserts.
bool hasEffectBadge(String key) => effectBadge(key) != null;

