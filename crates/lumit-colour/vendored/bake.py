"""Bake one BuiltinTransform style with the reference OpenColorIO library.

The grid, the shaper and their order are Lumit's — see bake.rs — and nothing
here may drift from them. Only the VALUES come from the reference library.

Run from this directory, with the config the fixture half uses:

    python bake.py "<style name>" > "<style name>.artefact"
"""
import sys, datetime, PyOpenColorIO as ocio

STYLE = sys.argv[1]
CONFIG = "../tests/fixtures/aces-cg/config.ocio"
CONFIG_NAME = "cg-config-v4.0.0_aces-v2.0_ocio-v2.5.ocio, release v4.0.0"
SIZE, MIN_LOG2, MAX_LOG2, OFFSET = 65, -8.0, 5.0, 0.00390625


def shaper_inverse(t):
    """Cube coordinate 0–1 back to the scene-linear value it stands for.

    The mirror of Shaper::Lg2::inverse in bake.rs. Transcribe it, do not
    re-derive it: an offset applied on the wrong side of the exponent shifts
    every sample by a fraction of a stop and still produces a picture.
    """
    return 2.0 ** (t * (MAX_LOG2 - MIN_LOG2) + MIN_LOG2) - OFFSET


# The style, resolved through a config so the library builds it exactly as it
# would for a view that names it.
t = ocio.BuiltinTransform(style=STYLE, direction=ocio.TRANSFORM_DIR_FORWARD)
cpu = ocio.Config.CreateFromFile(CONFIG).getProcessor(t).getDefaultCPUProcessor()

out = sys.stdout
out.write("lumit-colour artefact 1\n")
out.write(f"# style: {STYLE}\n")
out.write(f"# generated by: OpenColorIO {ocio.GetVersion()}, vendored/bake.py\n")
out.write(f"# generated from: {CONFIG_NAME}\n")
out.write(f"# generated on: {datetime.date.today()}\n")
out.write(
    f"# input domain: shaper lg2, min {MIN_LOG2:g}, max {MAX_LOG2:g}, offset {OFFSET}\n"
)
out.write(f"shaper lg2 {MIN_LOG2:g} {MAX_LOG2:g} {OFFSET}\n")
out.write(f"cube {SIZE}\n")

# RED FASTEST — blue is the outer loop. That is Lumit's order everywhere
# (docs/impl/lut.md §1) and it is the OPPOSITE of CLF's, so a script copied
# from a CLF writer transposes red and blue. The file is read back
# positionally, and a transposed cube is the classic silent LUT bug: it
# survives every test that only looks at neutrals.
#
# One applyRGB call per sample would be a quarter of a million round trips
# through the binding, so a whole red row goes at once through the in-place
# packed-buffer entry point. Nine significant digits is what an f32 needs to
# round-trip, and it is a third of the file size of Python's own repr.
last = SIZE - 1
grid = [shaper_inverse(i / last) for i in range(SIZE)]
import array

for b in range(SIZE):
    for g in range(SIZE):
        row = array.array("f", [0.0] * (SIZE * 3))
        for r in range(SIZE):
            row[r * 3], row[r * 3 + 1], row[r * 3 + 2] = grid[r], grid[g], grid[b]
        cpu.applyRGB(row)
        out.writelines(
            f"{row[i * 3]:.9g} {row[i * 3 + 1]:.9g} {row[i * 3 + 2]:.9g}\n"
            for i in range(SIZE)
        )
